//! Golden-file tests for `cafe-format` (Phase 4, see `AGENTS.md`).
//!
//! `cafe-format` only knows chunk framing + `IHDR` — it has no predictor
//! reversal or pixel semantics (that's `cafe-codec`, Phase 5+). So these
//! goldens exercise exactly what this crate is responsible for: signature
//! validation, chunk framing/CRC32, and `IHDR` parsing/validation. `IDAT`
//! payloads here are opaque bytes from this crate's point of view (still
//! shaped like real predictor-prefixed rows, so they'll be meaningful
//! fixtures once `cafe-codec` exists) — this crate never interprets them.
//!
//! Fixtures live in `golden/` (valid) and `golden/malformed/` (adversarial)
//! at the workspace root, generated by [`generate_golden_fixtures`] below.
//! That generator is `#[ignore]`d (not run on every `cargo test`) since the
//! fixtures are committed to the repo — run it manually with
//! `cargo test -p cafe-format --test golden_files -- --ignored` after a
//! deliberate, reviewed change to the fixture set itself.

use cafe_format::chunk::{read_chunk, write_chunk};
use cafe_format::constants::{
    COLOR_TYPE_GRAY, COLOR_TYPE_RGBA, COMPRESSION_METHOD_ZSTD_BIT, SAMPLE_FORMAT_UINT, SIGNATURE,
};
use cafe_format::error::CafeError;
use cafe_format::ihdr::{read_ihdr, Ihdr};
use cafe_format::validate_signature;
use std::path::{Path, PathBuf};

fn golden_dir() -> PathBuf {
    Path::new(env!("CARGO_MANIFEST_DIR"))
        .join("..")
        .join("..")
        .join("golden")
}

fn read_golden(name: &str) -> Vec<u8> {
    let path = golden_dir().join(name);
    std::fs::read(&path).unwrap_or_else(|e| panic!("failed to read golden {path:?}: {e}"))
}

fn read_malformed(name: &str) -> Vec<u8> {
    let path = golden_dir().join("malformed").join(name);
    std::fs::read(&path).unwrap_or_else(|e| panic!("failed to read golden {path:?}: {e}"))
}

/// Parses everything this crate knows how to parse: signature, `IHDR`, then
/// every following chunk via raw `read_chunk` (framing/CRC only — no
/// pixel/predictor interpretation). Returns the parsed `IHDR` and the list
/// of subsequent chunk types encountered, in order.
fn parse_minimal(buf: &[u8]) -> cafe_format::Result<(Ihdr, Vec<String>)> {
    let mut offset = validate_signature(buf)?;
    let (ihdr, next) = read_ihdr(buf, offset)?;
    offset = next;

    let mut types = Vec::new();
    while offset < buf.len() {
        let chunk = read_chunk(buf, offset)?;
        types.push(String::from_utf8_lossy(&chunk.chunk_type).to_string());
        offset = chunk.next_offset;
    }
    Ok((ihdr, types))
}

// --- Valid fixtures ---

#[test]
fn test_minimal_1x1_gray_parses_and_validates() {
    let buf = read_golden("minimal_1x1_gray.cafe");
    let (ihdr, types) = parse_minimal(&buf).expect("golden file should parse cleanly");
    assert_eq!(ihdr.width, 1);
    assert_eq!(ihdr.height, 1);
    assert_eq!(ihdr.bit_depth, 8);
    assert_eq!(ihdr.color_type, COLOR_TYPE_GRAY);
    assert_eq!(types, vec!["IDAT", "IEND"]);
}

#[test]
fn test_minimal_2x2_rgba_parses_and_validates() {
    let buf = read_golden("minimal_2x2_rgba.cafe");
    let (ihdr, types) = parse_minimal(&buf).expect("golden file should parse cleanly");
    assert_eq!(ihdr.width, 2);
    assert_eq!(ihdr.height, 2);
    assert_eq!(ihdr.bit_depth, 8);
    assert_eq!(ihdr.color_type, COLOR_TYPE_RGBA);
    assert_eq!(types, vec!["IDAT", "IEND"]);
}

