// --- Fixture generator (not run by default - see module doc comment) ---

#[test]
#[ignore = "regenerates golden fixtures; run manually after a deliberate, reviewed change"]
fn generate_golden_fixtures() {
    let dir = golden_dir();
    let malformed_dir = dir.join("malformed");
    std::fs::create_dir_all(&dir).unwrap();
    std::fs::create_dir_all(&malformed_dir).unwrap();

    // --- minimal_1x1_gray.cafe: smallest possible valid file ---
    let gray_ihdr = Ihdr {
        width: 1,
        height: 1,
        bit_depth: 8,
        sample_format: SAMPLE_FORMAT_UINT,
        color_type: COLOR_TYPE_GRAY,
        compression_method: 0, // no chunk in this file uses ZSTD
    };
    let mut buf = SIGNATURE.to_vec();
    buf.extend(gray_ihdr.to_chunk_bytes());
    // One row: predictor=0 (None) + one gray sample.
    buf.extend(write_chunk(b"IDAT", 0x00, &[0x00, 0x7F]));
    buf.extend(write_chunk(b"IEND", 0x00, b""));
    std::fs::write(dir.join("minimal_1x1_gray.cafe"), &buf).unwrap();

    // --- minimal_2x2_rgba.cafe: exercises multi-row, multi-channel, and
    // the ZSTD capability bit (still raw Flag - 2x2 RGBA is far too small
    // for compression to ever win the fallback race, spec section 3.2). ---
    let rgba_ihdr = Ihdr {
        width: 2,
        height: 2,
        bit_depth: 8,
        sample_format: SAMPLE_FORMAT_UINT,
        color_type: COLOR_TYPE_RGBA,
        compression_method: COMPRESSION_METHOD_ZSTD_BIT,
    };
    let mut buf = SIGNATURE.to_vec();
    buf.extend(rgba_ihdr.to_chunk_bytes());
    // Two rows, 2 pixels * 4 channels = 8 bytes/row, predictor=0 (None) each.
    let mut idat_payload = Vec::new();
    idat_payload.push(0x00); // row 0 predictor: None
    idat_payload.extend_from_slice(&[0x10, 0x20, 0x30, 0xFF, 0x11, 0x21, 0x31, 0xFF]);
    idat_payload.push(0x00); // row 1 predictor: None
    idat_payload.extend_from_slice(&[0x12, 0x22, 0x32, 0xFF, 0x13, 0x23, 0x33, 0xFF]);
    buf.extend(write_chunk(b"IDAT", 0x00, &idat_payload));
    buf.extend(write_chunk(b"IEND", 0x00, b""));
    std::fs::write(dir.join("minimal_2x2_rgba.cafe"), &buf).unwrap();

    // --- malformed/bad_signature.cafe: wrong magic bytes ---
    let mut buf = vec![0u8; 9];
    buf[0] = 0x89; // keep the high-bit-detection byte, corrupt the rest
    std::fs::write(malformed_dir.join("bad_signature.cafe"), &buf).unwrap();

    // --- malformed/truncated_header.cafe: EOF partway through IHDR's
    // chunk header (Length+Type+Flag is 9 bytes; only 5 are present) ---
    let mut buf = SIGNATURE.to_vec();
    let full_ihdr = gray_ihdr.to_chunk_bytes();
    buf.extend_from_slice(&full_ihdr[..5]);
    std::fs::write(malformed_dir.join("truncated_header.cafe"), &buf).unwrap();

    // --- malformed/crc_mismatch.cafe: valid framing, corrupted CRC32 ---
    let mut buf = SIGNATURE.to_vec();
    let mut ihdr_bytes = gray_ihdr.to_chunk_bytes();
    let last = ihdr_bytes.len() - 1;
    ihdr_bytes[last] ^= 0xFF; // flip a bit in the CRC32 footer
    buf.extend(ihdr_bytes);
    std::fs::write(malformed_dir.join("crc_mismatch.cafe"), &buf).unwrap();

    // --- malformed/invalid_ihdr_zero_width.cafe: framing/CRC valid, but
    // Width=0 violates spec section 4.1's "> 0" constraint ---
    let mut zero_width_ihdr = gray_ihdr;
    zero_width_ihdr.width = 0;
    let mut buf = SIGNATURE.to_vec();
    buf.extend(zero_width_ihdr.to_chunk_bytes());
    std::fs::write(malformed_dir.join("invalid_ihdr_zero_width.cafe"), &buf).unwrap();

    // --- malformed/forged_length.cafe: IHDR's Length field claims more
    // bytes than actually follow it (CWE-409-adjacent framing check,
    // spec section 8.1) ---
    let mut buf = SIGNATURE.to_vec();
    buf.extend_from_slice(&(1000u32).to_be_bytes()); // forged Length
    buf.extend_from_slice(b"IHDR");
    buf.push(0x00);
    buf.extend_from_slice(b"not actually 1000 bytes of data");
    std::fs::write(malformed_dir.join("forged_length.cafe"), &buf).unwrap();

    // --- malformed/wrong_first_chunk.cafe: first chunk after the
    // signature is not IHDR (spec section 5: IHDR must be first) ---
    let mut buf = SIGNATURE.to_vec();
    buf.extend(write_chunk(b"IDAT", 0x00, b"pixels before a header"));
    std::fs::write(malformed_dir.join("wrong_first_chunk.cafe"), &buf).unwrap();
}
