/// Encodes a single file and returns the Result (without unwrap) for tests of
/// rejection of invalid combinations.
fn encode_result(opts: &EncodeOptions, label: &str) -> Result<(), cafe::error::CafeError> {
    let dir = std::env::temp_dir().join("cafe_roundtrip");
    std::fs::create_dir_all(&dir).unwrap();
    let input_path = dir.join(format!("{label}_in.png"));
    let cafe_path = dir.join(format!("{label}.cafe"));
    make_test_image().save(&input_path).unwrap();
    encode(
        input_path.to_str().unwrap(),
        cafe_path.to_str().unwrap(),
        opts,
    )
}

#[test]
fn byte_shuffle_rejects_bpp3_rgb() {
    // RGB 8-bit has bpp=3, outside {2,4,8,16} → byte-shuffle must be rejected
    // at encode time (CWE-20: never produce a file with an invalid configuration).
    let opts = EncodeOptions {
        use_byte_shuffle: true,
        target_color_type: 2, // COLOR_TYPE_RGB (3 bytes/pixel)
        ..EncodeOptions::default()
    };
    let res = encode_result(&opts, "bs_reject_rgb");
    assert!(res.is_err(), "byte-shuffle with bpp=3 should be rejected");
}

#[test]
fn byte_shuffle_rejects_interlace() {
    // Byte-shuffle is incompatible with interlace → must be rejected at encode.
    let opts = EncodeOptions {
        use_byte_shuffle: true,
        interlace_method: 1, // Adam7
        ..EncodeOptions::default()
    };
    let res = encode_result(&opts, "bs_reject_interlace");
    assert!(res.is_err(), "byte-shuffle + interlace should be rejected");
}

// ---------------------------------------------------------------------------
// Structured metadata: jSON, eXIF, iCCP, xMPd and zDIC (ancillary chunks).
// ---------------------------------------------------------------------------

#[test]
fn roundtrip_metadata_chunks() {
    let dir = std::env::temp_dir().join("cafe_roundtrip");
    std::fs::create_dir_all(&dir).unwrap();

    let input_path = dir.join("meta_in.png");
    let cafe_path = dir.join("meta.cafe");
    let out_path = dir.join("meta_out.png");
    make_test_image().save(&input_path).unwrap();

    let mut json = std::collections::HashMap::new();
    json.insert(
        "camera".to_string(),
        serde_json::json!({ "model": "TestCam", "iso": 100 }),
    );
    json.insert(
        "author".to_string(),
        serde_json::json!({ "name": "CAFE Tests" }),
    );
    let exif = vec![0x45u8, 0x58, 0x49, 0x46, 0x00, 0x2A, 0xFF];
    let icc = vec![0xABu8; 96];
    let xmp = "<x:xmpmeta xmlns:x=\"adobe:ns:meta/\">test</x:xmpmeta>".to_string();
    let dict = vec![0x5Au8; 256];

    let opts = EncodeOptions {
        json_metadata: json.clone(),
        exif: Some(exif.clone()),
        icc_profile: Some(icc.clone()),
        xmp_metadata: Some(xmp.clone()),
        zstd_dictionary: Some(dict.clone()),
        ..EncodeOptions::default()
    };

    encode(
        input_path.to_str().unwrap(),
        cafe_path.to_str().unwrap(),
        &opts,
    )
    .expect("encode failed");

    let result =
        decode(cafe_path.to_str().unwrap(), out_path.to_str().unwrap()).expect("decode failed");

    assert_eq!(result.json_metadata, json, "jSON metadata diverged");
    assert_eq!(
        result.exif.as_deref(),
        Some(exif.as_slice()),
        "eXIF diverged"
    );
    assert_eq!(
        result.icc_profile.as_deref(),
        Some(icc.as_slice()),
        "iCCP diverged"
    );
    assert_eq!(
        result.xmp_metadata.as_deref(),
        Some(xmp.as_str()),
        "xMPd diverged"
    );
    assert_eq!(
        result.zstd_dictionary.as_deref(),
        Some(dict.as_slice()),
        "zDIC diverged"
    );
}

#[test]
fn roundtrip_metadata_empty_json() {
    // Empty jSON in the encoder → decoder must deliver an empty map (no panics).
    let dir = std::env::temp_dir().join("cafe_roundtrip");
    std::fs::create_dir_all(&dir).unwrap();

    let input_path = dir.join("meta_empty_in.png");
    let cafe_path = dir.join("meta_empty.cafe");
    let out_path = dir.join("meta_empty_out.png");
    make_test_image().save(&input_path).unwrap();

    let opts = EncodeOptions {
        ..EncodeOptions::default()
    };
    encode(
        input_path.to_str().unwrap(),
        cafe_path.to_str().unwrap(),
        &opts,
    )
    .expect("encode failed");
    let result =
        decode(cafe_path.to_str().unwrap(), out_path.to_str().unwrap()).expect("decode failed");
    assert!(result.json_metadata.is_empty());
    assert!(result.exif.is_none());
    assert!(result.icc_profile.is_none());
    assert!(result.xmp_metadata.is_none());
    assert!(result.zstd_dictionary.is_none());
}
