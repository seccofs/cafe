//! Round-trip tests for float/half sample_format and varied bit depths.
//!
//! Unlike `integration_test.rs` (which depends on an external image and
//! "skips" when it does not exist), these tests generate the input image in
//! memory via the `image` crate and verify the fidelity of the decoded pixels.

use cafe::{decode, encode, EncodeOptions};

const W: u32 = 16;
const H: u32 = 16;

fn make_test_image() -> image::RgbaImage {
    let mut img = image::RgbaImage::new(W, H);
    for (x, y, px) in img.enumerate_pixels_mut() {
        *px = image::Rgba([
            ((x * 17) % 256) as u8,
            ((y * 17) % 256) as u8,
            ((x * y + 1) % 256) as u8,
            ((x + y * 7) % 256) as u8,
        ]);
    }
    img
}

/// Expected gray value (same Y formula as the encoder).
fn gray_value(r: u8, g: u8, b: u8) -> u8 {
    ((299 * u32::from(r) + 587 * u32::from(g) + 114 * u32::from(b)) / 1000).min(255) as u8
}

/// Builds the expected RGBA after a round-trip that reduces the color type.
fn expected_for(color_type: u8) -> Vec<u8> {
    let src = make_test_image().into_raw();
    let mut expected = src.clone();
    for px in expected.chunks_exact_mut(4) {
        let (r, g, b) = (px[0], px[1], px[2]);
        match color_type {
            0 => {
                // GRAY: single channel replicated; alpha discarded
                let y = gray_value(r, g, b);
                px[0] = y;
                px[1] = y;
                px[2] = y;
                px[3] = 255;
            }
            2 => {
                // RGB: alpha discarded
                px[3] = 255;
            }
            4 => {
                // GRAY_ALPHA: gray replicated, alpha preserved
                let y = gray_value(r, g, b);
                px[0] = y;
                px[1] = y;
                px[2] = y;
            }
            _ => {}
        }
    }
    expected
}

/// Runs encode+decode of a generated image and returns the decoded RGBA pixels
/// (read back from the PNG generated by the decoder).
fn roundtrip(opts: &EncodeOptions, label: &str) -> Vec<u8> {
    let dir = std::env::temp_dir().join("cafe_roundtrip");
    std::fs::create_dir_all(&dir).unwrap();

    let input_path = dir.join(format!("{label}_in.png"));
    let cafe_path = dir.join(format!("{label}.cafe"));
    let out_path = dir.join(format!("{label}_out.png"));

    make_test_image().save(&input_path).unwrap();

    encode(
        input_path.to_str().unwrap(),
        cafe_path.to_str().unwrap(),
        opts,
    )
    .expect("encode failed");
    decode(cafe_path.to_str().unwrap(), out_path.to_str().unwrap()).expect("decode failed");

    let decoded = image::open(&out_path)
        .expect("failed to read decoded PNG")
        .to_rgba8();
    decoded.into_raw()
}

/// Compares RGBA pixels allowing a tolerance of ±2 per channel (float/half are
/// lossy in floating-point conversion).
fn assert_pixels_close(actual: &[u8], expected: &[u8], tolerance: u8) {
    assert_eq!(actual.len(), expected.len(), "pixel size differs");
    for (a, e) in actual.iter().zip(expected.iter()) {
        let diff = (*a).abs_diff(*e);
        assert!(
            diff <= tolerance,
            "pixel diverged: got {a}, expected {e} (tol {tolerance})"
        );
    }
}

#[test]
fn roundtrip_float_rgba() {
    let opts = EncodeOptions {
        sample_format: Some(1), // SAMPLE_FORMAT_FLOAT
        ..EncodeOptions::default()
    };
    let pixels = roundtrip(&opts, "float_rgba");
    let expected = expected_for(6);
    assert_pixels_close(&pixels, &expected, 2);
}

