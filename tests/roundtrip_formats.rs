// ---------------------------------------------------------------------------
// Tiling 2D (iDIM): end-to-end round-trip that exercises partition into tiles,
// one IDAT per tile in scan_order order and reassembly in the decoder.
// ---------------------------------------------------------------------------

/// Generates an RGBA image of arbitrary dims with a deterministic pattern.
fn make_image(w: u32, h: u32) -> image::RgbaImage {
    let mut img = image::RgbaImage::new(w, h);
    for (x, y, px) in img.enumerate_pixels_mut() {
        *px = image::Rgba([
            ((x * 7 + y * 3) % 256) as u8,
            ((x * 13 + y % 256) % 256) as u8,
            ((x + y * 29) % 256) as u8,
            ((x * 3 + y * 5) % 256) as u8,
        ]);
    }
    img
}

/// Round-trip of an image with arbitrary dims; returns decoded RGBA pixels.
fn roundtrip_size(opts: &EncodeOptions, w: u32, h: u32, label: &str) -> Vec<u8> {
    roundtrip_image(make_image(w, h), opts, label)
}

fn roundtrip_image(img: image::RgbaImage, opts: &EncodeOptions, label: &str) -> Vec<u8> {
    let dir = std::env::temp_dir().join("cafe_roundtrip");
    std::fs::create_dir_all(&dir).unwrap();

    let input_path = dir.join(format!("{label}_in.png"));
    let cafe_path = dir.join(format!("{label}.cafe"));
    let out_path = dir.join(format!("{label}_out.png"));

    img.save(&input_path).unwrap();
    encode(
        input_path.to_str().unwrap(),
        cafe_path.to_str().unwrap(),
        opts,
    )
    .expect("encode failed");
    decode(cafe_path.to_str().unwrap(), out_path.to_str().unwrap()).expect("decode failed");

    image::open(&out_path)
        .expect("failed to read decoded PNG")
        .to_rgba8()
        .into_raw()
}

fn idim_tiling(tile_w: u16, tile_h: u16, scan_order: u8) -> cafe::iDim {
    cafe::iDim::new(tile_w, tile_h, 33, 23, scan_order)
}

#[test]
fn roundtrip_tiling_rowmajor() {
    // Image 33x23, tile 8x8 → 5x4 = 20 tiles (partial edges).
    let opts = EncodeOptions {
        idim: Some(idim_tiling(8, 8, 0)),
        ..EncodeOptions::default()
    };
    let pixels = roundtrip_size(&opts, 33, 23, "tiling_rowmajor");
    assert_pixels_close(&pixels, &make_image(33, 23).into_raw(), 0);
}

